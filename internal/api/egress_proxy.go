// renderSquidConf builds the whole proxy config from the per-project allow-lists.
//
// The shape is: one listener per project, and an ACL that only matches that
// listener's name. A request therefore can only ever be evaluated against its
// own project's domains — there is no rule that could match traffic from two
// projects, which is the property that makes the port-per-project scheme sound.
//
// Four things here are load-bearing security-wise, not style:
//
//   - `http_access deny all` last. squid's default when nothing matches is to
//     allow, so the deny has to be explicit and it has to be final.
//   - CONNECT restricted to 443. Without it, an allow-listed hostname becomes a
//     tunnel to any port on that host — `CONNECT allowed.example.com:22` would
//     otherwise be permitted, which turns one entry into shell access.
//   - No ssl_bump. squid matches the hostname from the CONNECT and then dials it
//     itself; it never terminates TLS, so nothing has to trust a platform CA and
//     request bodies stay opaque to the platform.
//   - A project with no domains gets its listener but no allow rule, so it fails
//     closed rather than inheriting a default.
func renderSquidConf(targets []store.EgressProxyTarget) string {
	var b strings.Builder

	b.WriteString(`# Generated by control-plane — do not edit.
#
# Per-project egress allow-list. One http_port per project; the myportname ACL
# ties a listener to exactly one project's domain list.

# Never rewrite or cache anything: this is a policy checkpoint, not a cache.
cache deny all
cache_store_log none
cache_log stdio:/dev/stdout

# access.log is the audit trail and the only place a blocked request shows up.
# TCP_DENIED lines are how an admin learns what a project still needs.
logfile_rotate 0
access_log stdio:/dev/stdout squid

# No via/forwarded headers announcing the proxy, and no client address leak.
via off
forwarded_for delete
httpd_suppress_version_string on

# DNS through the cluster resolver, so a project cannot smuggle lookups past it.
dns_nameservers 10.43.0.10

acl SSL_ports port 443
acl Safe_ports port 80
acl Safe_ports port 443
acl CONNECT method CONNECT

# CONNECT only to 443. An allow-listed name must not become a tunnel to an
# arbitrary port on that host.
http_access deny CONNECT !SSL_ports
http_access deny !Safe_ports

# Health probe for the Deployment, before any project rule.
acl localhost_src src 127.0.0.1/32
http_access allow localhost_src manager
http_access deny manager

`)

	for _, t := range targets {
		name := "proj_" + strings.ReplaceAll(t.Slug, "-", "_")
		fmt.Fprintf(&b, "# --- %s ---\n", t.Slug)
		fmt.Fprintf(&b, "http_port %d name=%s\n", t.Port, t.Slug)
		fmt.Fprintf(&b, "acl %s_port myportname %s\n", name, t.Slug)

		if len(t.Domains) == 0 {
			// Listener exists so the pod gets a connection refused-free error
			// (503 from squid, logged) instead of a black hole, but nothing is
			// allowed through it.
			fmt.Fprintf(&b, "# no domains allow-listed — everything through this listener is denied\n\n")
			continue
		}
		var https, http []string
		for _, d := range t.Domains {
			if d.Port == 80 {
				http = append(http, d.Value)
			} else {
				https = append(https, d.Value)
			}
		}
		sort.Strings(https)
		sort.Strings(http)
		if len(https) > 0 {
			fmt.Fprintf(&b, "acl %s_https dstdomain %s\n", name, strings.Join(https, " "))
			fmt.Fprintf(&b, "http_access allow %s_port CONNECT %s_https SSL_ports\n", name, name)
			// Plain GET to an https-allowed host is harmless and often how
			// health checks are written; keep it on 443's list.
			fmt.Fprintf(&b, "http_access allow %s_port %s_https\n", name, name)
		}
		if len(http) > 0 {
			fmt.Fprintf(&b, "acl %s_http dstdomain %s\n", name, strings.Join(http, " "))
			fmt.Fprintf(&b, "http_access allow %s_port %s_http\n", name, name)
		}
		b.WriteString("\n")
	}

	b.WriteString(`# Anything not explicitly allowed above. squid defaults to allow when no rule
# matches, so this line is what makes the whole file deny-by-default.
http_access deny all
`)
	return b.String()
}

// syncEgressProxy re-renders the proxy config from the database and pushes it to
// the cluster. Called whenever an allow-list changes and once at startup.
//
// Best-effort by design at the call sites: a project's endpoint rules and its
// NetworkPolicy are already consistent by the time this runs, and failing the
// admin's request because the proxy reload hiccuped would leave them unsure
// whether their edit was saved. The error is returned so callers can log it.
func (s *Server) syncEgressProxy(ctx context.Context) error {
	if s.deployer == nil {
		return nil
	}
	targets, err := s.store.ListEgressProxyTargets(ctx)
	if err != nil {
		return fmt.Errorf("list proxy targets: %w", err)
	}
	ports := make([]int32, 0, len(targets))
	for _, t := range targets {
		ports = append(ports, int32(t.Port))
	}
	return s.deployer.EnsureEgressProxy(ctx, renderSquidConf(targets), ports)
}

// SweepEgressProxyAtStartup brings the proxy in line with the database once at
// boot, so a config change that happened while the control plane was down (or a
// hand-edited ConfigMap) converges without waiting for the next allow-list edit.
func (s *Server) SweepEgressProxyAtStartup(ctx context.Context) {
	if err := s.syncEgressProxy(ctx); err != nil {
		log.Printf("egress proxy sweep: %v", err)
	}
}
